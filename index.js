#!/usr/bin/env node


import { Command } from 'commander';
import { main } from './src/cli.js';
import fs from 'fs';
import path from 'path';
import { verifyBaseBranchExists } from './src/gitUtils.js';

const CONFIG_PATH = path.resolve(process.cwd(), '.mo3ta-coverage.json');

function readConfig() {
  console.log(`Reading config from: ${CONFIG_PATH}`);
  
  if (fs.existsSync(CONFIG_PATH)) {
    return JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8'));
  }
  return {};
}

function writeConfig(config) {
  fs.writeFileSync(CONFIG_PATH, JSON.stringify(config, null, 2));
  console.log(`Updated config: ${JSON.stringify(config, null, 2)}`);
}

const program = new Command();

const PkgPath = new URL('./package.json', import.meta.url);
const pkgVersion = JSON.parse(fs.readFileSync(PkgPath, 'utf8')).version;

program
  .name('mo3ta-coverage')
  .version(pkgVersion, '-V, --version', 'Show the installed version')
  .description('Run tests and report uncovered changed lines in a PR. Checks cumulative coverage for all changed lines against a specified limit. Useful for CI and code review workflows.');

program
  .option('--base <branch>', 'Base branch to compare against (e.g., origin/main)')
  .option('--lcov <path>', 'Path to lcov.info file generated by test coverage tools', 'coverage/lcov.info')
  .option('--limit <percent>', 'Minimum required coverage percentage for all changed lines (e.g., 80)', '80')
  .option('--showCovered <bool>', 'Show covered changed lines in the output', false)
  .option('--mode <mode>', 'Execution mode: fast, smart, or full', 'smart')
  .option('--depth <number>', 'Smart mode max reverse-dependency depth (1 = direct importers, 2 = also importers of importers)', '2')
  .option('--files <files...>', 'Scan only these files instead of detecting changed files (space- or comma-separated)')
  .option('--filesFrom <path>', 'Read the list of files to scan from a newline-separated file')
  .enablePositionalOptions(); // used to allow using same options in subcommands

// Usage help text (printed next to --help)
program.showHelpAfterError('(add --help for a list of options)');
program.addHelpText('after', `
Examples:
$ mo3ta-coverage --mode smart --base origin/main --limit 80
$ mo3ta-coverage --files src/a.js,src/b.ts --base origin/main
$ mo3ta-coverage --filesFrom changed.txt --base origin/main
$ mo3ta-coverage --mode fast --showCovered true
$ mo3ta-coverage config --mode smart --depth 2
$ mo3ta-coverage --version

Modes:
  fast   Naming-convention matches, plus a direct import-scan fallback.
  smart  Naming + reverse-import walk, bounded by --depth (default 2).
  full   Passes changed files to "jest --findRelatedTests".

See README.md for details: https://github.com/MahmoudMabrok/mo3ta-coverage`);


program
  .command('config')
  .description('Set or get configuration options')
  .option('--base <branch>', 'Set default base branch')
  .option('--mode <mode>', 'Set default mode (fast/smart/full)')
  .option('--depth <number>', 'Set default smart-mode depth (1-10)')
  .action((opts) => {
    let config = readConfig();

    let updated = false;

    if (opts.base) {
      verifyBaseBranchExists(opts.base);
      
      config.base = opts.base;
      updated = true;
      console.log(`Default base branch set to: ${opts.base}`);
    }

    if (opts.mode !== undefined) {
      const normalizedMode = String(opts.mode).toLowerCase();
      if (!['fast', 'smart', 'full'].includes(normalizedMode)) {
        console.error(`Invalid mode: ${opts.mode}. Expected one of: fast, smart, full.`);
        process.exit(1);
      }
      config.mode = normalizedMode;
      updated = true;
      console.log(`Default mode set to: ${config.mode}`);
    }

    if (opts.depth !== undefined) {
      const normalizedDepth = Number.parseInt(opts.depth, 10);
      if (!Number.isInteger(normalizedDepth) || normalizedDepth < 1 || normalizedDepth > 10) {
        console.error(`Invalid depth: ${opts.depth}. Expected an integer between 1 and 10.`);
        process.exit(1);
      }
      config.depth = normalizedDepth;
      updated = true;
      console.log(`Default smart-mode depth set to: ${config.depth}`);
    }
    if (updated) {
      writeConfig(config);
    } else {
      console.log('Current config:', config);
    }
    process.exit(0);
  })
  .enablePositionalOptions()


program.action((opts) => {
  const config = readConfig();
  const options = program.opts();

  const modeFromCli = program.getOptionValueSource('mode') === 'cli';
  const depthFromCli = program.getOptionValueSource('depth') === 'cli';
 
  // Use config base if not provided in CLI
  if (!options.base && config.base) {
    options.base = config.base;
  } else if (!options.base) {
    options.base = 'origin/main';
  }

  if (!modeFromCli && config.mode) {
    options.mode = config.mode;
  }

  options.mode = String(options.mode || 'smart').toLowerCase();
  if (!['fast', 'smart', 'full'].includes(options.mode)) {
    console.error(`Invalid mode: ${options.mode}. Expected one of: fast, smart, full.`);
    process.exit(1);
  }

  if (options.mode === 'smart') {
    if (!depthFromCli && config.depth !== undefined) {
      options.depth = String(config.depth);
    }

    const depth = Number.parseInt(options.depth, 10);
    if (!Number.isInteger(depth) || depth < 1 || depth > 10) {
      console.error(`Invalid depth: ${options.depth}. Expected an integer between 1 and 10.`);
      process.exit(1);
    }
    options.depth = depth;
  }

  console.log(`Final options: ${JSON.stringify(options, null, 2)}`);

  main(options);
});

await program.parseAsync(process.argv);