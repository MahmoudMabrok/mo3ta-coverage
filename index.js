#!/usr/bin/env node


import { Command } from 'commander';
import { main } from './src/cli.js';
import fs from 'fs';
import path from 'path';
import { verifyBaseBranchExists } from './src/gitUtils.js';

const CONFIG_PATH = path.resolve(process.cwd(), '.mo3ta-coverage.json');

function readConfig() {
  console.log(`Reading config from: ${CONFIG_PATH}`);
  
  if (fs.existsSync(CONFIG_PATH)) {
    return JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8'));
  }
  return {};
}

function writeConfig(config) {
  fs.writeFileSync(CONFIG_PATH, JSON.stringify(config, null, 2));
  console.log(`Updated config: ${JSON.stringify(config, null, 2)}`);
}

const program = new Command();

program
  .name('mo3ta-coverage')
  .description('Run tests and report uncovered changed lines in a PR. Checks cumulative coverage for all changed lines against a specified limit. Useful for CI and code review workflows.')
  .version('1.0.13', '-v, --version', 'Output the current version');

program
  .option('--base <branch>', 'Base branch to compare against (e.g., origin/main)')
  .option('--lcov <path>', 'Path to lcov.info file generated by test coverage tools', 'coverage/lcov.info')
  .option('--limit <percent>', 'Minimum required coverage percentage for all changed lines (e.g., 80)', '80')
  .option('--showCovered <bool>', 'Show covered changed lines in the output', false)
  .option('--mode <mode>', 'Execution mode: fast, smart, or full', 'smart')
  .option('--maxDepth <number>', 'Maximum reverse dependency depth for smart mode', '3')
  .enablePositionalOptions(); // used to allow using same options in subcommands


program
  .command('config')
  .description('Set or get configuration options')
  .option('--base <branch>', 'Set default base branch')
  .option('--mode <mode>', 'Set default mode (fast/smart/full)')
  .option('--maxDepth <number>', 'Set default reverse dependency depth for smart mode')
  .action((opts) => {
    let config = readConfig();

    let updated = false;

    if (opts.base) {
      verifyBaseBranchExists(opts.base);
      
      config.base = opts.base;
      updated = true;
      console.log(`Default base branch set to: ${opts.base}`);
    }

    if (opts.mode !== undefined) {
      const normalizedMode = String(opts.mode).toLowerCase();
      if (!['fast', 'smart', 'full'].includes(normalizedMode)) {
        console.error(`Invalid mode: ${opts.mode}. Expected one of: fast, smart, full.`);
        process.exit(1);
      }
      config.mode = normalizedMode;
      updated = true;
      console.log(`Default mode set to: ${config.mode}`);
    }

    if (opts.maxDepth !== undefined) {
      const parsedMaxDepth = parseInt(opts.maxDepth, 10);
      if (!Number.isInteger(parsedMaxDepth) || parsedMaxDepth < 0) {
        console.error(`Invalid maxDepth: ${opts.maxDepth}. Expected a non-negative integer.`);
        process.exit(1);
      }
      config.maxDepth = parsedMaxDepth;
      updated = true;
      console.log(`Default max depth set to: ${config.maxDepth}`);
    }

    if (updated) {
      writeConfig(config);
    } else {
      console.log('Current config:', config);
    }
    process.exit(0);
  })
  .enablePositionalOptions()


program.action((opts) => {
  const config = readConfig();
  const options = program.opts();
 
  // Use config base if not provided in CLI
  if (!options.base && config.base) {
    options.base = config.base;
  } else if (!options.base) {
    options.base = 'origin/main';
  }

  if (!options.mode && config.mode) {
    options.mode = config.mode;
  }

  if ((options.maxDepth === undefined || options.maxDepth === '3') && config.maxDepth !== undefined) {
    options.maxDepth = config.maxDepth;
  }

  // Validate mode
  options.mode = options.mode || 'smart'; // Default to smart if not provided
  
  // Check if mode is invalid (boolean, empty string, etc.)
  if (typeof options.mode === 'boolean' || options.mode === '') {
    console.error(`❌ Missing or invalid --mode value.`);
    console.error(`Available options: fast, smart, full`);
    console.error(`\nMode descriptions:`);
    console.error(`  • fast  - Direct execution of mapped test files only`);
    console.error(`  • smart - Combine source and mapped test files with reverse deps (recommended)`);
    console.error(`  • full  - Run mapped tests through Jest --findRelatedTests`);
    console.error(`\nExample: mo3ta-coverage --mode smart`);
    process.exit(1);
  }

  options.mode = String(options.mode).toLowerCase();
  if (!['fast', 'smart', 'full'].includes(options.mode)) {
    console.error(`❌ Invalid mode: "${options.mode}"`);
    console.error(`Available options: fast, smart, full`);
    console.error(`\nMode descriptions:`);
    console.error(`  • fast  - Direct execution of mapped test files only`);
    console.error(`  • smart - Combine source and mapped test files with reverse deps (recommended)`);
    console.error(`  • full  - Run mapped tests through Jest --findRelatedTests`);
    console.error(`\nExample: mo3ta-coverage --mode smart`);
    process.exit(1);
  }

  options.maxDepth = parseInt(options.maxDepth ?? 3, 10);
  if (!Number.isInteger(options.maxDepth) || options.maxDepth < 0) {
    console.error(`Invalid maxDepth: ${options.maxDepth}. Expected a non-negative integer.`);
    process.exit(1);
  }

  console.log(`Final options: ${JSON.stringify(options, null, 2)}`);

  main(options);
});

await program.parseAsync(process.argv);